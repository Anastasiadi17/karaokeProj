from functools import lru_cache
from pathlib import Path

from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(
        env_prefix="KARAOKE_",
        env_file=".env",
        env_file_encoding="utf-8",
        extra="ignore",
    )

    data_dir: Path = Path("data")
    db_path: Path = Path("data/karaoke.db")

    separator: str = "demucs"

    max_duration_sec: int = 600
    # Байт на секунду звука отличается между разрешёнными форматами в 36 раз
    # (mp3 128 кбит/с — 16 000 Б/с, wav 96 кГц/24 бит стерео — 576 000 Б/с),
    # поэтому одним числом в байтах обещание в секундах не выражается. Лимит
    # размера — защита от исчерпания ресурсов, а продуктовое обещание — это
    # max_duration_sec; защита не должна срабатывать раньше обещания.
    # 200 МиБ выбраны так, чтобы 600 с влезали для всего, что приносит
    # обычный пользователь, включая студийный wav 48 кГц/24 бит (172,8 МБ).
    # На 100 МиБ такой файл упирался в размер уже на 364 с, то есть сервис
    # отказывал на шести минутах, обещая десять.
    # Hi-res 96 кГц/24 бит по-прежнему упрётся в размер на 364 с — это
    # задокументированная граница, а не недосмотр.
    # Себестоимость это почти не двигает: demucs всегда пишет стемы в
    # 44,1 кГц, поэтому хранение после обработки от исходника не зависит,
    # растёт только временный диск на время загрузки.
    max_upload_bytes: int = 209715200
    file_ttl_hours: int = 24
    # m4a исключён: libsndfile (через soundfile) его не читает —
    # sf.available_formats() отдаёт MP3, но не M4A/AAC/MP4. Обещать формат,
    # который тут же отвергается как нечитаемый, хуже, чем не обещать вовсе.
    allowed_formats: tuple[str, ...] = ("mp3", "wav", "flac")

    # Сколько ждать текущую задачу при выключении, прежде чем закрыть базу.
    # Замер на RTX 5060 на предельной длительности: трек в
    # max_duration_sec=600 обрабатывается за 20,9 с вместе с загрузкой
    # модели. 120 — примерно пятикратный запас на карту послабее и на
    # копирование стемов (по 100 МиБ каждый), и при этом приемлемое время
    # ответа на Ctrl+C. Это потолок ожидания, а не гарантия: на откате на
    # CPU обработка длится куда дольше, и тогда выключение честно логирует,
    # что задача не досчитана.
    shutdown_wait_sec: float = 120.0

    # Сколько живёт сессия и одноразовая ссылка входа. Тридцать дней — чтобы
    # человек не логинился каждый раз, пятнадцать минут — чтобы ссылка,
    # оставшаяся в чужой почте или в истории браузера, быстро протухала.
    session_ttl_days: int = 30
    login_token_ttl_min: int = 15

    # Адрес, по которому сервис виден снаружи: из него собирается ссылка в
    # письме. По умолчанию — локальный запуск.
    public_base_url: str = "http://127.0.0.1:8000"

    # Отдавать ссылку входа прямо в ответе вместо письма. Только для
    # разработки и сквозных тестов: с этим флагом вход в чужой аккаунт
    # получает любой, кто знает адрес. При старте пишется предупреждение.
    expose_login_link: bool = False

    # Операций разделения в календарный месяц на бесплатном тарифе (4.1).
    free_monthly_operations: int = 3

    # Каталог собранного фронтенда (`web/dist` после `npm run build`).
    # Пусто — API работает сам по себе, как и раньше; тогда браузер и API
    # сводит в один origin что-то снаружи: прокси Vite в разработке или
    # обратный прокси в продакшене. Заполнено — тот же процесс раздаёт
    # статику в корне, и одинаковый источник получается без единой сторонней
    # детали. Это не замена обратному прокси там, где он уже есть, а
    # кратчайший путь поднять всё целиком одной командой.
    web_dist: Path | None = None

    # Сколько DELETE ждёт замок изменения треков, прежде чем ответить 503.
    # Замок держит воркер на время записи двух дорожек — около секунды на
    # стемах по 100 МиБ, так что 30 с это примерно тридцатикратный запас и
    # при этом заметно меньше обычного таймаута HTTP-клиента. Воркеру и
    # фоновой уборке таймаут не нужен: сдаваться им некуда.
    track_lock_timeout_sec: float = 30.0


@lru_cache
def get_settings() -> Settings:
    return Settings()
